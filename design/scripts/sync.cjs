// Synchronize prototype metadata from this repository.
// Vox 尚无 Directory.Build.props / csproj：存在则读取，缺失时回退到内置声明。
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
function sync() {
  let version = '0.1.0';
  let website = 'https://codewf.com';
  try {
    const props = fs.readFileSync(path.join(root, 'Directory.Build.props'), 'utf8');
    version = props.match(/<Version>([^<]+)<\/Version>/)[1];
    website = (props.match(/<PackageProjectUrl>([^<]+)<\/PackageProjectUrl>/) || [])[1] || website;
  } catch (_) { /* 仓库骨架未就位，使用内置值 */ }
  const project = {
    version, website,
    copyright: 'Copyright © 2026 沙漠尽头的狼 / CodeWF',
    repository: 'https://github.com/dotnet9/Vox',
    license: 'MIT',
    slogan: '一处落笔，处处有声。'
  };
  const out = (file, value) => {
    const target = path.join(root, 'design', file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== value) fs.writeFileSync(target, value, 'utf8');
  };
  out('assets/project-info.js', '// Generated by design/scripts/sync.cjs.\nwindow.VoxProject = ' + JSON.stringify(project, null, 2) + ';\n');
  return version;
}
if (require.main === module) console.log('Prototype metadata synchronized: Vox ' + sync());
module.exports = sync;
