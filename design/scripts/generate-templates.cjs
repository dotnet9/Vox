// 生成原型模板数据：src/Vox.Core/Templates/*.md（内置，产品真值）+ design/assets/templates-user/*.md（"我的"演示）
// → design/assets/generated/templates-data.js（window.VoxTemplates），Vox.html 经 <script> 加载，file:// 与 http 均可用。
// 用法: node design/scripts/generate-templates.cjs
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');

/* 内置模板显式排序（分类分组 → 阅读顺序）；未列出的文件按文件名追加，新增模板无需改这里也能被发现。 */
const BUILTIN_ORDER = [
  '可行性分析报告.md', '项目开发计划.md', '软件需求规格说明.md', '软件设计说明.md',
  '测试计划.md', '测试报告.md', '项目开发总结报告.md',
  '运维服务方案.md', '事件故障报告.md', '变更记录.md', '巡检报告.md', '应急预案.md',
];
const USER_DIR = path.join(root, 'design/assets/templates-user');

function parseDoc(file) {
  const raw = fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n|\r/g, '\n');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) throw new Error('缺少 front matter: ' + file);
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    const v = kv[2].trim();
    meta[kv[1]] = /^\[.*\]$/.test(v) ? v.slice(1, -1).split(',').map(s => s.trim()).filter(Boolean) : v;
  }
  for (const key of ['title', 'description', 'kind', 'standard'])
    if (!meta[key]) throw new Error('front matter 缺少 ' + key + ': ' + file);
  if (!['dev', 'ops', 'my'].includes(meta.kind)) throw new Error('kind 必须是 dev/ops/my: ' + file);
  return {
    id: path.basename(file, '.md'), cat: meta.kind, name: meta.title, std: meta.standard,
    desc: meta.description, categories: meta.categories || [], tags: meta.tags || [],
    draft: meta.draft !== 'false', md: raw.slice(m[0].length).replace(/^\n+/, '').trimEnd() + '\n',
  };
}

const builtinDir = path.join(root, 'src/Vox.Core/Templates');
const ordered = BUILTIN_ORDER.map(f => path.join(builtinDir, f))
  .concat(fs.readdirSync(builtinDir).filter(f => f.endsWith('.md') && !BUILTIN_ORDER.includes(f)).sort().map(f => path.join(builtinDir, f)));
const templates = ordered.map(parseDoc)
  .concat(fs.readdirSync(USER_DIR).filter(f => f.endsWith('.md')).sort().map(f => parseDoc(path.join(USER_DIR, f))));

const out = '// Generated by design/scripts/generate-templates.cjs — do not edit.\n'
  + '// 内置模板源文件: src/Vox.Core/Templates/*.md（产品真值，桌面端实现直接内嵌同一批文件）。\n'
  + '// "我的"两篇为原型演示数据，模拟用户模板目录（正式实现从 %AppData%/Vox/templates 动态读取）。\n'
  + 'window.VoxTemplates = ' + JSON.stringify(templates, null, 1).replace(/\n/g, '\n') + ';\n';
const target = path.join(root, 'design/assets/generated/templates-data.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) fs.writeFileSync(target, out, 'utf8');
console.log('OK: ' + templates.length + ' 篇模板 → design/assets/generated/templates-data.js（内置 ' + (templates.length - 2) + ' + 我的 2）');
